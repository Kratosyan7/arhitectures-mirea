#
# Задание №2. Две реализации перевода строки в НИЖНИЙ регистр на
# ассемблере RISC-V (своя реализация той же функции, что и tolower.c).
#
# Соглашение о вызове:
#   a0 - адрес входной строки
#   a1 - адрес выходной строки
#   возврат a0 - длина (число записанных байт, включая завершающий 0)
#

# --------------------------------------------------------------------
# tolower_branch: прямой перевод по методичке - два ветвления на диапазон
# 'A'..'Z'. Регистры: t2 - символ, t3 - граница, t5 - начало выхода.
# --------------------------------------------------------------------
.global tolower_branch
tolower_branch:
    mv   t5, a1
lb_loop:
    lb   t2, 0(a0)
    addi a0, a0, 1
    li   t3, 'A'            # если символ < 'A' -> пропустить
    blt  t2, t3, lb_cont
    li   t3, 'Z'            # если символ > 'Z' -> пропустить
    bgt  t2, t3, lb_cont
    addi t2, t2, 32         # 'a'-'A' = 32: перевод в нижний регистр
lb_cont:
    sb   t2, 0(a1)
    addi a1, a1, 1
    bnez t2, lb_loop
    sub  a0, a1, t5
    ret

# --------------------------------------------------------------------
# tolower_nobranch: оптимизация приёмами главы 10 - БЕЗ ветвлений в теле.
# Сдвиг диапазона (c - 'A'), беззнаковое сравнение < 26 через sltiu даёт
# маску {0,1}, умножаем на 0x20 и ИЛИ с символом: бит 0x20 ставится
# только для заглавных букв. Единственное ветвление - условие цикла.
# Регистры: t2 - символ, t4 - c-'A', t3 - флаг/маска, t5 - начало выхода.
# --------------------------------------------------------------------
.global tolower_nobranch
tolower_nobranch:
    mv   t5, a1
lnb_loop:
    lbu  t2, 0(a0)          # без расширения знака
    addi a0, a0, 1
    addi t4, t2, -'A'       # c - 'A'
    sltiu t3, t4, 26        # 1, если 0 <= c-'A' < 26 (заглавная буква)
    slli t3, t3, 5          # *32 -> либо 0x20, либо 0
    or   t2, t2, t3         # поставить бит 0x20 только для заглавных
    sb   t2, 0(a1)
    addi a1, a1, 1
    bnez t2, lnb_loop
    sub  a0, a1, t5
    ret
