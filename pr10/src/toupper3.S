#
# Задание №1. Вариант перевода в ВЕРХНИЙ регистр без ветвлений.
# Сужение задачи: только буквы. Сброс бита 0x20 маской 0xDF,
# по Листингу 10.7 методички (здесь оформлено подпрограммой, а не макросом).
#
# a0 - адрес входной строки, a1 - адрес выходной строки
# возврат: a0 - длина
#
# ВНИМАНИЕ: корректно только для букв. Для прочих ASCII-символов
# искажает данные (например, пробел 0x20 -> 0x00 завершит цикл).
#
.global toupper3
toupper3:
    mv   t5, a1
loop3:
    lb   t2, 0(a0)
    addi a0, a0, 1
    andi t2, t2, 0xdf       # сбросить бит 0x20 (без ветвлений)
    sb   t2, 0(a1)
    addi a1, a1, 1
    bnez t2, loop3
    sub  a0, a1, t5
    ret
