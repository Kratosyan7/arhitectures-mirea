#
# Задание №2. Две реализации замены пробелов на '_' на ассемблере
# RISC-V (своя реализация той же функции, что и replspace.c).
#
# Соглашение о вызове:
#   a0 - адрес входной строки
#   a1 - адрес выходной строки
#   возврат a0 - длина (число записанных байт, включая завершающий 0)
#

# --------------------------------------------------------------------
# repl_branch: прямая реализация с ветвлением - сравнить символ с ' '
# (0x20) и при совпадении записать '_' (0x5F).
# Регистры: t2 - символ, t3 - константа, t5 - начало выхода.
# --------------------------------------------------------------------
.global repl_branch
repl_branch:
    mv   t5, a1
rb_loop:
    lb   t2, 0(a0)
    addi a0, a0, 1
    li   t3, ' '           # 0x20 - пробел
    bne  t2, t3, rb_cont   # если не пробел -> не менять
    li   t2, '_'           # 0x5F - подчёркивание
rb_cont:
    sb   t2, 0(a1)
    addi a1, a1, 1
    bnez t2, rb_loop
    sub  a0, a1, t5
    ret

# --------------------------------------------------------------------
# repl_nobranch: БЕЗ ветвления в теле. Признак пробела is_space = (c==0x20)
# вычисляется сравнением, разворачивается в маску 0x3F и прибавляется к
# символу: 0x20 + 0x3F = 0x5F ('_'), прочие символы не меняются
# (прибавляется 0). Единственное ветвление - условие цикла.
# Регистры: t2 - символ, t4 - c XOR ' ', t3 - маска, t5 - начало выхода.
# --------------------------------------------------------------------
.global repl_nobranch
repl_nobranch:
    mv   t5, a1
rnb_loop:
    lbu  t2, 0(a0)         # без расширения знака
    addi a0, a0, 1
    xori t4, t2, ' '       # 0, если символ - пробел
    seqz t3, t4            # 1, если пробел, иначе 0
    neg  t3, t3            # 0xFF..F, если пробел, иначе 0
    andi t3, t3, 0x3F      # 0x3F, если пробел, иначе 0
    add  t2, t2, t3        # пробел 0x20 + 0x3F = 0x5F; иначе без изменений
    sb   t2, 0(a1)
    addi a1, a1, 1
    bnez t2, rnb_loop
    sub  a0, a1, t5
    ret
