#
# Задание №4. Листинг 10.14 - функция toupper БЕЗ проверки длины буфера.
# Именно отсутствие контроля длины делает возможным переполнение буфера.
#
# a0 - адрес входной строки
# a1 - адрес выходной строки
# s0 - исходный выходной указатель (для расчёта длины)
# t2 - текущий символ, t3 - регистр для сравнения
#
.global toupper
toupper:
    addi sp, sp, -16        # выделить 16 байт на стеке
    sd   ra, 8(sp)          # сохранить адрес возврата
    sd   s0, 0(sp)          # сохранить s0
    mv   s0, a1             # сохранить начало выходной строки
# Цикл до нулевого символа. Длина НЕ проверяется!
loop:
    lb   t2, 0(a0)          # загрузить символ
    addi a0, a0, 1          # сдвинуть указатель входа
    li   t3, 'z'            # если > 'z' -> пропустить
    bgt  t2, t3, cont
    li   t3, 'a'            # если < 'a' -> пропустить
    blt  t2, t3, cont
    addi t2, t2, ('A'-'a')  # перевод в верхний регистр
cont:
    sb   t2, 0(a1)          # сохранить символ в выходной буфер
    addi a1, a1, 1          # сдвинуть указатель выхода
    li   t3, 0
    bne  t2, t3, loop       # повторять, пока символ не нулевой

    sub  a0, a1, s0         # длина = разность указателей
    ld   s0, 0(sp)          # восстановить s0
    ld   ra, 8(sp)          # восстановить ra
    addi sp, sp, 16         # освободить стек
    ret
