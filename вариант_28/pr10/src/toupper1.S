#
# Задание №1. Вариант 1 функции перевода в ВЕРХНИЙ регистр.
# Базовый вариант с двумя ветвлениями ("обратная логика"),
# по Листингам 10.1-10.2 и 10.14 методички.
#
# a0 - адрес входной строки
# a1 - адрес выходной строки
# возврат: a0 - длина (число записанных байт, включая завершающий 0)
#
# t2 - текущий символ
# t3 - регистр для сравнения
# t5 - исходный указатель выхода (для расчёта длины)
#
.global toupper1
toupper1:
    mv   t5, a1              # сохранить начало выходной строки
loop1:
    lb   t2, 0(a0)          # загрузить символ
    addi a0, a0, 1          # сдвинуть указатель входа
    li   t3, 'z'            # если символ > 'z' -> пропустить
    bgt  t2, t3, cont1
    li   t3, 'a'            # если символ < 'a' -> пропустить
    blt  t2, t3, cont1
    addi t2, t2, -32        # 'A'-'a' = -32: перевод в верхний регистр
cont1:
    sb   t2, 0(a1)          # сохранить символ
    addi a1, a1, 1
    bnez t2, loop1          # повторять, пока символ не нулевой
    sub  a0, a1, t5         # длина = разность указателей
    ret
