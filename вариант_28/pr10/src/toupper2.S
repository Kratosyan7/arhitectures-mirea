#
# Задание №1. Оптимизированный вариант перевода в ВЕРХНИЙ регистр.
# Сдвиг диапазона + одно беззнаковое сравнение (bgeu),
# по Листингам 10.3-10.5 методички.
#
# a0 - адрес входной строки, a1 - адрес выходной строки
# возврат: a0 - длина
#
# t2 - текущий символ, t3 - константа 26, t4 - символ минус 'a'
# t5 - исходный указатель выхода
#
.global toupper2
toupper2:
    mv   t5, a1
loop2:
    lb   t2, 0(a0)
    addi a0, a0, 1
    addi t4, t2, -'a'       # сдвиг диапазона: нижняя граница -> 0
    li   t3, 26             # 'z'-'a'+1
    bgeu t4, t3, cont2      # беззнаковое: вне [0;25] -> не строчная буква
    addi t2, t2, -32        # перевод в верхний регистр
cont2:
    sb   t2, 0(a1)
    addi a1, a1, 1
    bnez t2, loop2
    sub  a0, a1, t5
    ret
