# Дополнительное задание: функция mytoupper_utf8 – перевод строки в
# верхний регистр с поддержкой латиницы (ASCII) и кириллицы в UTF-8.
#
# int mytoupper_utf8(const char *in, char *out);
# a0 – адрес входной строки, a1 – адрес выходной строки
# Возвращает длину выходной строки вместе с завершающим нулём
# (так же, как mytoupper из листинга 9.8).
#
# Кодировка UTF-8 кириллицы (2 байта на букву):
#   а..п  U+0430..U+043F = D0 B0..D0 BF  ->  А..П = D0 90..D0 9F (2-й байт - 0x20)
#   р..я  U+0440..U+044F = D1 80..D1 8F  ->  Р..Я = D0 A0..D0 AF (D1->D0, 2-й байт + 0x20)
#   ё     U+0451         = D1 91         ->  Ё    = D0 81
#
# t2 – текущий байт, t4 – следующий байт, t3 – константы для сравнения,
# t5 – исходный адрес выходной строки. Функция листовая, стек не нужен.

.global mytoupper_utf8

mytoupper_utf8:
        mv   t5, a1              # запомнить начало выходной строки
next:   lbu  t2, 0(a0)           # байт без знакового расширения (0..255)
        addi a0, a0, 1
        li   t3, 0xD0
        beq  t2, t3, lead_d0     # первый байт букв а..п
        li   t3, 0xD1
        beq  t2, t3, lead_d1     # первый байт букв р..я, ё
        li   t3, 'a'             # ASCII: 'a' <= c <= 'z' ?
        bltu t2, t3, store
        li   t3, 'z'
        bgtu t2, t3, store
        addi t2, t2, ('A'-'a')   # c -= 0x20
        j    store

lead_d0:                         # D0 xx: строчные а..п имеют xx = B0..BF
        lbu  t4, 0(a0)
        li   t3, 0xB0
        bltu t4, t3, store       # не строчная буква – копируем как есть
        li   t3, 0xBF
        bgtu t4, t3, store
        addi t4, t4, -0x20       # B0..BF -> 90..9F
        j    store2

lead_d1:                         # D1 xx: р..я (80..8F) и ё (91)
        lbu  t4, 0(a0)
        li   t3, 0x91
        beq  t4, t3, yo
        li   t3, 0x80
        bltu t4, t3, store
        li   t3, 0x8F
        bgtu t4, t3, store
        addi t4, t4, 0x20        # 80..8F -> A0..AF
        li   t2, 0xD0            # первый байт заглавных Р..Я – D0
        j    store2
yo:     li   t2, 0xD0            # ё (D1 91) -> Ё (D0 81)
        li   t4, 0x81

store2:                          # записать двухбайтовую букву
        sb   t2, 0(a1)
        sb   t4, 1(a1)
        addi a1, a1, 2
        addi a0, a0, 1           # второй байт входа уже обработан
        j    next

store:  sb   t2, 0(a1)           # записать один байт
        addi a1, a1, 1
        bnez t2, next            # продолжать до завершающего нуля

        sub  a0, a1, t5          # длина вместе с нулём
        ret
